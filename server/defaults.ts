export function workbenchDefaults(appearance: PaseoAppearance | null, scheme: "dark" | "light"): Record<string, unknown> {
  // Paseo Dark / Paseo Light: Dark / Light Modern with Paseo's colors (theme-extension.ts).
  const theme = scheme === "light" ? PASEO_LIGHT : PASEO_DARK;
  const defaults: Record<string, unknown> = {
    // Follows Paseo's mode. VS Code web would start in its light theme otherwise.
    "workbench.colorTheme": theme,

    // Paseo is the AI surface: no second chat panel, button or Copilot prompts.
    "chat.disableAIFeatures": true,
    "workbench.secondarySideBar.defaultVisibility": "hidden",

    // VS Code's activity bar and side bar on the right edge, next to Paseo's own sidebar.
    "workbench.sideBar.location": "right",

    // Open straight on the workspace.
    "workbench.startupEditor": "none",
    "workbench.welcomePage.walkthroughs.openOnInstall": false,
    "workbench.tips.enabled": false,
    "workbench.enableExperiments": false,
    "workbench.remoteIndicator.showExtensionRecommendations": false,
    // The plugin pins and updates the VS Code build itself.
    "update.mode": "none",
  };
  if (appearance) {
    // Paseo Theme's file already holds these colors, but VS Code caches a theme's colors and
    // does not re-read its file while the extension version is unchanged. The same colors,
    // scoped to the Paseo theme only, apply at once. Other themes are left untouched.
    defaults["workbench.colorCustomizations"] = { [`[${theme}]`]: chromeColors(appearance.colors) };
    if (appearance.fontFamily) {
      defaults["editor.fontFamily"] = appearance.fontFamily;
      defaults["terminal.integrated.fontFamily"] = appearance.fontFamily;
    }
    if (appearance.fontSize) {
      defaults["editor.fontSize"] = appearance.fontSize;
      defaults["terminal.integrated.fontSize"] = appearance.fontSize;
    }
  }
  return defaults;
}
